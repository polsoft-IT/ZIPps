"""ZIPps - generator plikow (tekst, binarne, .pyc, C/C++, RAW...)."""
import json
import math
import os
import py_compile
from datetime import datetime

from zipps_pkg.version import __version__, __app_name__
from zipps_pkg.core import PackerError, Empty
from zipps_pkg.settings_mod import settings
from zipps_pkg.logging_mod import Logger

# =====================================================================
#  Generator plikow
# =====================================================================

PY_SCRIPT_TEMPLATE = '''#!/usr/bin/env python3
"""{module} - plik wygenerowany przez {app}."""

import sys


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    print("Hello from {module}! Arguments:", argv)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''

C_TEMPLATE = (
    "#include <stdio.h>\n\n"
    "int main(void) {\n"
    "    printf(\"Hello from C!\\n\");\n"
    "    return 0;\n"
    "}\n"
)

CPP_TEMPLATE = (
    "#include <iostream>\n\n"
    "int main() {\n"
    "    std::cout << \"Hello from C++!\" << std::endl;\n"
    "    return 0;\n"
    "}\n"
)

H_TEMPLATE = (
    "#ifndef {name_upper}_H\n"
    "#define {name_upper}_H\n\n"
    "/* Header file generated by {app} */\n\n"
    "#ifdef __cplusplus\n"
    "extern \"C\" {\n"
    "#endif\n\n"
    "/* Function declarations */\n"
    "void hello(void);\n\n"
    "#ifdef __cplusplus\n"
    "}\n"
    "#endif\n\n"
    "#endif /* {name_upper}_H */\n"
)


class FileGenerator:
    """Tworzy rozne rodzaje plikow (tekst, binarny, .pyc, C, C++, RAW, JSON, MD)."""

    def __init__(self, logger: Logger | None = None):
        self.logger = logger or Empty()

    # -- pomocnicze ---------------------------------------------------
    @staticmethod
    def _ensure_dir(folder: str):
        if not folder:
            raise PackerError("no output folder")
        os.makedirs(folder, exist_ok=True)

    @staticmethod
    def _ext(ext: str, default: str = "") -> str:
        """Normalizuje rozszerzenie pliku (dodaje kropke, wycina spacje)."""
        ext = (ext or "").strip()
        if not ext:
            return default
        # Remove dots and add a single one at the beginning
        ext = ext.lstrip(".")
        if ext:
            ext = "." + ext
        return ext

    @staticmethod
    def _validate_name(name: str) -> str:
        """Waliduje i normalizuje nazwe pliku (usuwa niedozwolone znaki)."""
        if not name:
            return "file"
        # Remove invalid characters for Windows/Linux filenames
        invalid_chars = '<>:"/\\|?*'
        for char in invalid_chars:
            name = name.replace(char, "_")
        # Remove leading/trailing spaces and dots
        name = name.strip(". ")
        if not name:
            return "file"
        return name

    def _done(self, path: str) -> str:
        self.logger.log(settings.t("generated") + path)
        return path

    # -- generatory ---------------------------------------------------
    def generate_text_file(self, folder: str, name: str, ext: str, content: str) -> str:
        self._ensure_dir(folder)
        name = self._validate_name(name) or "file"
        path = os.path.join(folder, name + self._ext(ext, ".txt"))
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(content or "")
        return self._done(path)

    def generate_binary_file(self, folder: str, name: str, ext: str, size: int) -> str:
        self._ensure_dir(folder)
        size = int(size)
        if size <= 0:
            raise PackerError(settings.t("invalid_size"))
        name = self._validate_name(name) or "binary"
        path = os.path.join(folder, name + self._ext(ext, ".bin"))
        with open(path, "wb") as f:
            written = 0
            while written < size:
                chunk = min(1024 * 1024, size - written)
                f.write(os.urandom(chunk))
                written += chunk
        return self._done(path)

    def generate_pyc(self, folder: str, name: str, code: str, keep_source: bool = True) -> str:
        self._ensure_dir(folder)
        name = self._validate_name(name) or "module"
        py_path = os.path.join(folder, name + ".py")
        with open(py_path, "w", encoding="utf-8") as f:
            f.write(code or "")
        pyc_path = py_path + "c"
        py_compile.compile(py_path, cfile=pyc_path, doraise=True)
        if not keep_source:
            try:
                os.remove(py_path)
            except OSError:
                pass
        return self._done(pyc_path)

    def generate_python_script(self, folder: str, name: str, code: str = "") -> str:
        self._ensure_dir(folder)
        name = self._validate_name(name) or "script"
        path = os.path.join(folder, name + ".py")
        content = code or PY_SCRIPT_TEMPLATE.format(
            module=name, app="%s v%s" % (__app_name__, __version__))
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        return self._done(path)

    def generate_c_file(self, folder: str, name: str, content: str = "") -> str:
        self._ensure_dir(folder)
        name = self._validate_name(name) or "main"
        path = os.path.join(folder, name + ".c")
        with open(path, "w", encoding="utf-8") as f:
            f.write(content or C_TEMPLATE)
        return self._done(path)

    def generate_cpp_file(self, folder: str, name: str, content: str = "") -> str:
        self._ensure_dir(folder)
        name = self._validate_name(name) or "main"
        path = os.path.join(folder, name + ".cpp")
        with open(path, "w", encoding="utf-8") as f:
            f.write(content or CPP_TEMPLATE)
        return self._done(path)

    def generate_h_file(self, folder: str, name: str, content: str = "") -> str:
        self._ensure_dir(folder)
        name = self._validate_name(name) or "header"
        path = os.path.join(folder, name + ".h")
        name_upper = name.upper().replace("-", "_").replace(" ", "_")
        template_content = content or H_TEMPLATE.format(
            name_upper=name_upper,
            app="%s v%s" % (__app_name__, __version__)
        )
        with open(path, "w", encoding="utf-8") as f:
            f.write(template_content)
        return self._done(path)

    def generate_dat_file(self, folder: str, name: str, size: int) -> str:
        """Generates binary .dat file (data file)."""
        self._ensure_dir(folder)
        size = int(size)
        if size <= 0:
            raise PackerError(settings.t("invalid_size"))
        name = self._validate_name(name) or "data"
        path = os.path.join(folder, name + ".dat")
        with open(path, "wb") as f:
            written = 0
            while written < size:
                chunk = min(1024 * 1024, size - written)
                f.write(os.urandom(chunk))
                written += chunk
        return self._done(path)

    def generate_img_file(self, folder: str, name: str, size: int) -> str:
        """Generates binary .img file (disk image)."""
        self._ensure_dir(folder)
        size = int(size)
        if size <= 0:
            raise PackerError(settings.t("invalid_size"))
        name = self._validate_name(name) or "image"
        path = os.path.join(folder, name + ".img")
        with open(path, "wb") as f:
            written = 0
            while written < size:
                chunk = min(1024 * 1024, size - written)
                f.write(os.urandom(chunk))
                written += chunk
        return self._done(path)

    def generate_blob_file(self, folder: str, name: str, size: int) -> str:
        """Generates binary .blob file (binary large object)."""
        self._ensure_dir(folder)
        size = int(size)
        if size <= 0:
            raise PackerError(settings.t("invalid_size"))
        name = self._validate_name(name) or "blob"
        path = os.path.join(folder, name + ".blob")
        with open(path, "wb") as f:
            written = 0
            while written < size:
                chunk = min(1024 * 1024, size - written)
                f.write(os.urandom(chunk))
                written += chunk
        return self._done(path)

    def generate_raw_image(self, folder: str, name: str, width: int, height: int,
                           pattern: str = "gradient") -> str:
        """8-bitowy obraz RAW; wzory: gradient, noise, checker, xr, plasma."""
        self._ensure_dir(folder)
        width = max(1, int(width))
        height = max(1, int(height))
        name = self._validate_name(name) or "image"
        path = os.path.join(folder, name + ".raw")
        if pattern == "noise":
            data = os.urandom(width * height)
        elif pattern == "checker":
            data = bytearray(width * height)
            cell = 16
            for y in range(height):
                row = y // cell
                base = y * width
                for x in range(0, width, cell):
                    value = 230 if ((x // cell) + row) % 2 else 30
                    end = min(width, x + cell)
                    data[base + x:base + end] = bytes([value]) * (end - x)
        elif pattern == "xr":
            data = bytearray(width * height)
            for y in range(height):
                v = int(255 * (y / max(1, height - 1)))
                data[y * width:(y + 1) * width] = bytes([v]) * width
        elif pattern == "plasma":
            data = bytearray(width * height)
            wdt = max(1, width - 1)
            hgt = max(1, height - 1)
            idx = 0
            for y in range(height):
                fy = y / hgt
                for x in range(width):
                    fx = x / wdt
                    value = 127 + 127 * math.sin(fx * math.pi * 3) * math.cos(fy * math.pi * 2)
                    data[idx] = int(max(0, min(255, value)))
                    idx += 1
        else:
            data = bytearray(width * height)
            wdt = max(1, width - 1)
            for y in range(height):
                row = bytearray(int(255 * (x / wdt)) for x in range(width))
                data[y * width:(y + 1) * width] = row
        with open(path, "wb") as f:
            f.write(data)
        return self._done(path)

    def generate_json_file(self, folder: str, name: str, content: str = "") -> str:
        self._ensure_dir(folder)
        name = self._validate_name(name) or "data"
        path = os.path.join(folder, name + ".json")
        if content.strip():
            try:
                payload = json.loads(content)
            except ValueError:
                raise PackerError("invalid JSON")
        else:
            payload = {
                "generated": datetime.now().isoformat(timespec="seconds"),
                "tool": "%s %s" % (__app_name__, __version__),
                "items": [],
            }
        with open(path, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2, ensure_ascii=False)
        return self._done(path)

    def generate_markdown_file(self, folder: str, name: str, content: str = "") -> str:
        self._ensure_dir(folder)
        name = self._validate_name(name) or "README"
        path = os.path.join(folder, name + ".md")
        text = content.strip() or (
            "# %s\n\n%s\n\n## Opis\n\n- [ ] punkt 1\n- [ ] punkt 2\n\n"
            "```python\nprint('Hello')\n```\n" % (name or "Dokument",
                                                  datetime.now().strftime("%Y-%m-%d"))
        )
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        return self._done(path)

